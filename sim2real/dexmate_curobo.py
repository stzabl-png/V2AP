# ── robot base transform (Table-B frame) ─────────────────────────────────────

def get_dexmate_base_transform() -> tuple[np.ndarray, np.ndarray]:
    yaw = np.deg2rad(DEXMATE_ROBOT_ORIENTATION[2])
    c, s = np.cos(yaw), np.sin(yaw)
    T = np.eye(4)
    T[:3, :3] = np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])
    T[:3, 3]  = DEXMATE_ROBOT_POSITION
    return T, np.linalg.inv(T)


def world_to_robot_pose_dexmate(
    pos_w: np.ndarray, quat_wxyz_w: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    _, T_rw = get_dexmate_base_transform()
    pos_r = (T_rw @ np.append(pos_w, 1.0))[:3]
    R_w  = Rotation.from_quat([quat_wxyz_w[1], quat_wxyz_w[2], quat_wxyz_w[3], quat_wxyz_w[0]])
    R_rw = Rotation.from_matrix(T_rw[:3, :3])
    R_r  = R_rw * R_w
    q    = R_r.as_quat()
    return pos_r, np.array([q[3], q[0], q[1], q[2]])



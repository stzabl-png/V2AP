def ensure_dexmate_curobo_config() -> Path:
    """
    Write vega_1.yml + collision spheres into curobo's config tree if missing.
    Returns path to the yml file (for user information).
    """
    import yaml

    # Locate curobo content dir
    content_root: Path | None = None
    for _c in sys.path:
        candidate = Path(_c) / "curobo" / "content" / "configs" / "robot"
        if candidate.is_dir():
            content_root = candidate
            break
    if content_root is None:
        cprint("[dexmate_curobo] Could not find curobo content dir; skipping yml generation.", "yellow")
        return DEXMATE_CUROBO_YML

    yml_dst = content_root / "dexmate_vega_1.yml"
    spheres_dst = content_root.parent / "robot" / "spheres" / "dexmate_vega_1.yml"

    if not yml_dst.exists():
        usd_abs = str((SIM2REAL_DIR / "assets_dexmate" / "vega_1.usd").resolve())
        yml_dst.write_text(DEXMATE_YML_TEMPLATE.format(usd_path=usd_abs))
        cprint(f"[dexmate_curobo] wrote {yml_dst}", "green")

    spheres_dst.parent.mkdir(parents=True, exist_ok=True)
    if not spheres_dst.exists():
        spheres_dst.write_text(DEXMATE_SPHERES_TEMPLATE)
        cprint(f"[dexmate_curobo] wrote {spheres_dst}", "green")

    return yml_dst


# ── world config builder (mirrors curobo_world.py helpers) ───────────────────

def _build_dexmate_world_config(
    table_pos_r: np.ndarray,
    ground_pos_r: np.ndarray,
) -> dict:
    return {
        "cuboid": {
            "table": {
                "dims": list(TABLE_SCALE),
                "pose": [*table_pos_r.tolist(), 1, 0, 0, 0],
            },
            "ground": {
                "dims": [20.0, 20.0, 0.1],
                "pose": [*ground_pos_r.tolist(), 1, 0, 0, 0],
            },
        }
    }


# ── init CuRobo for Dexmate ──────────────────────────────────────────────────

def init_dexmate_curobo() -> Any:
    from curobo.wrap.reacher.motion_gen import MotionGen, MotionGenConfig

    extra = "/home/vision/isaacsim/kit/python/bin:/usr/local/cuda/bin"
    if extra not in os.environ.get("PATH", ""):
        os.environ["PATH"] = extra + ":" + os.environ.get("PATH", "")

    ensure_dexmate_curobo_config()

    _, T_rw = get_dexmate_base_transform()
    table_pos_r  = (T_rw @ np.append(TABLE_B_POSITION, 1.0))[:3]
    ground_pos_r = (T_rw @ np.array([0, 0, -0.005, 1.0]))[:3]
    world_config = _build_dexmate_world_config(table_pos_r, ground_pos_r)

    cprint("   [dexmate-curobo] loading MotionGenConfig...", "yellow")
    t0 = time.time()
    mg_config = MotionGenConfig.load_from_robot_config(
        "dexmate_vega_1.yml", world_config, interpolation_dt=0.02
    )
    cprint(f"   [dexmate-curobo] config loaded in {time.time()-t0:.1f}s", "yellow")

    mg = MotionGen(mg_config)

    # Warmup with heartbeat
    TIMEOUT = int(os.environ.get("CUROBO_WARMUP_TIMEOUT", "600"))
    done  = threading.Event()
    exc_: list[Exception] = []

    def _warmup():
        try:
            mg.warmup()
        except Exception as e:
            exc_.append(e)
        finally:
            done.set()

    def _hb():
        t1 = time.time()
        while not done.is_set():
            done.wait(timeout=10)
            if not done.is_set():
                print(f"   [dexmate-warmup] {int(time.time()-t1)}s...", flush=True)
                if time.time() - t1 > TIMEOUT:
                    os.kill(os.getpid(), 9)

    threading.Thread(target=_warmup, daemon=True).start()
    threading.Thread(target=_hb,      daemon=True).start()
    done.wait()
    if exc_:
        raise RuntimeError(f"Dexmate CuRobo warmup failed: {exc_[0]}") from exc_[0]
    cprint(f"   [dexmate-curobo] ready ✅ ({time.time()-t0:.1f}s)", "green")
    return mg


# ── plan one trajectory ───────────────────────────────────────────────────────

def plan_dexmate_trajectory(
    motion_gen: Any,
    current_joints: np.ndarray,    # (7,) right-arm joints
    target_pos_world: np.ndarray,
    target_quat_wxyz_world: np.ndarray,
    label: str = "",
) -> np.ndarray | None:
    from curobo.types.math import Pose
    from curobo.types.robot import JointState as CuJointState
    from curobo.wrap.reacher.motion_gen import MotionGenPlanConfig

    pos_r, quat_r = world_to_robot_pose_dexmate(target_pos_world, target_quat_wxyz_world)
    start_state = CuJointState.from_position(
        torch.tensor(current_joints, dtype=torch.float32).unsqueeze(0).cuda(),
    )
    goal_pose = Pose.from_list([
        float(pos_r[0]), float(pos_r[1]), float(pos_r[2]),
        float(quat_r[0]), float(quat_r[1]), float(quat_r[2]), float(quat_r[3]),
    ])
    result = motion_gen.plan_single(
        start_state, goal_pose,
        MotionGenPlanConfig(max_attempts=10, enable_graph=True, enable_opt=True),
    )
    ok = result.success.item() if hasattr(result.success, "item") else bool(result.success)
    if ok:
        traj = result.get_interpolated_plan()
        cprint(f"      [{label}] Dexmate plan OK: {traj.position.shape[0]} steps", "green")
        return traj.position.cpu().numpy()
    cprint(f"      [{label}] Dexmate plan FAILED", "red")
    return None
